/**
 * Aplica o modificador Unicode Fitzpatrick de tom de pele quando o emoji suporta variação.
 */
export function applySkinTone(emoji: string, modifier: string, supportsSkinTone?: boolean): string {
  if (!supportsSkinTone || !modifier) return emoji;
  // Remove modificadores existentes antes de aplicar o novo
  const stripped = emoji.replace(/[\u{1F3FB}-\u{1F3FF}]/gu, "");
  // Se o emoji termina com variation selector FE0F, substitui pelo modificador de pele
  const base = stripped.replace(/\uFE0F$/u, "");
  const codePoints = Array.from(base);
  if (codePoints.length === 1) {
    return codePoints[0] + modifier;
  }
  // Sequências compostas ZWJ (ex: 🤷‍♂️ -> insere modificador logo após o primeiro caractere humano)
  return codePoints[0] + modifier + codePoints.slice(1).join("");
}

